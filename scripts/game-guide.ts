export async function checkGuide(): Promise<string[]> {
  const pages = await renderGuide();
  const stale: string[] = [];
  for (const [name, body] of Object.entries(pages)) {
    const actual = await readFile(join(GUIDE_DIR, `${name}.md`), "utf8").catch(() => "");
    if (actual !== body) stale.push(`${name}.md`);
  }
  return stale;
}

export function wikiMarkdown(body: string): string {
  return body.replace(/\]\((Home|Cards|Builds|Enemies|Stages|Mechanics)\.md\)/g, "]($1)");
}

if (import.meta.main) {
  if (Bun.argv.includes("--check")) {
    const stale = await checkGuide();
    if (stale.length) {
      console.error(
        `游戏说明需要更新：${stale.join(", ")}。请核对机制文案后运行 bun run docs:generate。`,
      );
      process.exitCode = 1;
    } else console.log("游戏说明与当前规则一致。");
  } else {
    await mkdir(GUIDE_DIR, { recursive: true });
    for (const [name, body] of Object.entries(await renderGuide()))
      await writeFile(join(GUIDE_DIR, `${name}.md`), body);
    console.log("已生成 docs/game-guide/ 的完整游戏说明与 Wiki 页面。");
  }
}
