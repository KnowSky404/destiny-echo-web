export async function checkGuide(): Promise<string[]> {
  const pages = await renderGuide();
  const stale: string[] = [];
  for (const [name, body] of Object.entries(pages)) {
    const actual = await readFile(join(GUIDE_DIR, `${name}.md`), "utf8").catch(() => "");
    if (actual !== body) stale.push(`${name}.md`);
    for (const match of body.matchAll(
      /(?:\]\(|src=")(\.\.\/assets\/[^)"#]+)(?:#[^)"]*)?(?:\)|")/g,
    )) {
      const asset = match[1];
      if (
        asset &&
        !(await access(join(GUIDE_DIR, asset)).then(
          () => true,
          () => false,
        ))
      )
        stale.push(`${name}.md: missing asset ${asset}`);
    }
  }
  return stale;
}

export function wikiMarkdown(body: string): string {
  return body
    .replace(/\]\(([A-Za-z][A-Za-z0-9-]*)\.md(#[^)]*)?\)/g, "]($1$2)")
    .replace(
      /(\]\(|src=")\.\.\/assets\/([^)"]+)(\)|")/g,
      "$1https://raw.githubusercontent.com/wiki/KnowSky404/destiny-echo-web/assets/$2$3",
    );
}

